/** PNG Info: read the generation parameters embedded in a PNG and send them to a tab. */
final class PngInfoTab(ctx: UiContext, actions: ImageActions):
  val image = new SimpleStringProperty("")
  private val drop = new ImageDropZone(ctx, image, "PNG with generation parameters", 300)
  private val text = new TextArea()
  text.setEditable(false)
  text.setWrapText(true)
  text.setPrefRowCount(7)
  text.getStyleClass.add("infotext")
  text.setPromptText("Parameters appear here")

  final class Row(k: String, v: String):
    def getKey: String = k
    def getValue: String = v
  private val rows = FXCollections.observableArrayList[Row]()
  private val table = new TableView[Row](rows)
  table.setColumnResizePolicy(TableView.CONSTRAINED_RESIZE_POLICY_FLEX_LAST_COLUMN)
  private val kc = new TableColumn[Row, String]("Field")
  kc.setCellValueFactory(c => new SimpleStringProperty(c.getValue.getKey))
  kc.setPrefWidth(150)
  kc.setMaxWidth(220)
  private val vc = new TableColumn[Row, String]("Value")
  vc.setCellValueFactory(c => new SimpleStringProperty(c.getValue.getValue))
  table.getColumns.addAll(kc, vc)
  table.setPlaceholder(W.label("Drop a PNG generated by A1111 / reForge / SDNUI", "muted"))
  table.setPrefHeight(240)
  table.setMinWidth(0)
  table.setPrefWidth(200)

  private def current: Option[(Path, String)] =
    Option(image.get).filter(_.nonEmpty).map(Paths.get(_)).zip(Option(text.getText).filter(_.nonEmpty))

  private def send(mode: Mode): Unit =
    Option(image.get).filter(_.nonEmpty) match
      case None => ctx.info("Drop a PNG first")
      case Some(p) =>
        if mode == Mode.Txt2Img then current.fold(ctx.info("This image has no parameters"))((_, t) => actions.restore(t))
        else actions.sendTo(mode, Paths.get(p), Option(text.getText).filter(_.nonEmpty))

  private val buttons = W.hbox(
    6,
    W.button("⇢ txt2img", "Restore these parameters in txt2img")(send(Mode.Txt2Img)),
    W.button("⇢ img2img", "Send image and parameters to img2img")(send(Mode.Img2Img)),
    W.button("⇢ Inpaint", "Send image and parameters to Inpaint")(send(Mode.Inpaint))
  )

  image.addListener((_, _, p) =>
    rows.clear()
    text.clear()
    Option(p).filter(_.nonEmpty).foreach { path =>
      Fx.async(PngMetadata.readTexts(Paths.get(path))) { texts =>
        val params = texts.get(PngMetadata.ParametersKey)
        text.setText(params.getOrElse(if texts.isEmpty then "(no text chunks)" else texts.map((k, v) => s"$k: $v").mkString("\n")))
        params.foreach { t =>
          val pi = Infotext.parse(t)
          rows.add(Row("Prompt", pi.prompt))
          if pi.negativePrompt.nonEmpty then rows.add(Row("Negative prompt", pi.negativePrompt))
          pi.fields.foreach((k, v) => rows.add(Row(k, v)))
        }
      }(e => ctx.error(s"Cannot read PNG: ${Fx.message(e)}"))
    }
  )

  val node: ScrollPane =
    val v = new VBox(10, W.card("Image", drop.node), W.card("Parameters", text, table, buttons))
    v.setPadding(new Insets(10, 12, 16, 12))
    val sp = new ScrollPane(v)
    sp.setFitToWidth(true)
    sp.setHbarPolicy(ScrollPane.ScrollBarPolicy.NEVER)
    sp

/** Extras: upscale an image with one of the engine upscalers. */
final class ExtrasTab(ctx: UiContext, initialUpscaler: String, initialScale: Double):
  val image = new SimpleStringProperty("")
  val upscaler = new SimpleStringProperty(initialUpscaler)
  val scale = new SimpleDoubleProperty(initialScale)
  private val drop = new ImageDropZone(ctx, image, "Image to upscale", 280)
  private val result = new SimpleStringProperty("")
  def comparisonPair: Option[(Path, Path)] =
    for a <- Option(image.get).filter(_.nonEmpty); b <- Option(result.get).filter(_.nonEmpty) yield Paths.get(a) -> Paths.get(b)
  private val resultView = new ZoomImageView()
  resultView.setPrefHeight(320)
  resultView.setMinHeight(240)
  resultView.getStyleClass.add("result-view")
  private val resultInfo = W.label("", "hint")
  private val spinner = new ProgressIndicator()
  spinner.setVisible(false)
  spinner.setPrefSize(22, 22)

  def showResult(path: Path): Unit =
    result.set(path.toString)
    resultView.setUserData(path)
    ImageFiles.load(path.toString).foreach(resultView.setImage)
    resultInfo.setText(path.toString)

  private val run: Button = W.button("⤢ Upscale", "Upscale the image with the selected upscaler", Seq("accent-button"))(upscale())
  private def upscale(): Unit =
    val src = Option(image.get).filter(_.nonEmpty)
    val up = Option(upscaler.get).filter(_.nonEmpty)
    (src, up) match
      case (None, _) => ctx.info("Add an image first")
      case (_, None) => ctx.info("Choose an upscaler (put ESRGAN models in models/upscalers)")
      case (Some(s), Some(u)) =>
        run.setDisable(true)
        spinner.setVisible(true)
        val sc = scale.get
        Fx.async(ctx.services.generator.upscaleImage(Paths.get(s), u, sc)) { out =>
          run.setDisable(false)
          spinner.setVisible(false)
          showResult(out)
          ctx.success("Upscaled")
        } { e =>
          run.setDisable(false)
          spinner.setVisible(false)
          ctx.error(s"Upscale failed: ${Fx.message(e)}")
        }

  private val upscalerBox = W.combo(ctx.catalog.upscalers, upscaler)
  upscalerBox.setPromptText("No upscalers — put ESRGAN models in models/upscalers")
  private def pickDefault(): Unit =
    val items = ctx.catalog.upscalers
    if !items.isEmpty && (upscaler.get == null || upscaler.get.isEmpty || !items.contains(upscaler.get)) then upscaler.set(items.get(0))
  ctx.catalog.upscalers.addListener((_: javafx.collections.ListChangeListener.Change[? <: String]) => pickDefault())
  pickDefault()

  private val f = W.form()
    .add("Upscaler", upscalerBox, "ESRGAN / RealESRGAN models from models/upscalers")
    .add("Scale", W.doubleSlider(scale, 1, 8, 0.25), "Resize factor")

  private val compareButton = W.button("Send to Comparison", "Compare upscale input and output") {
    comparisonPair.fold(ctx.info("Upscale an image first"))((a, b) => ctx.comparePair(a, b))
  }
  def refreshComparisonOptions(): Unit =
    val option = ctx.services.settings.comparisonSendButtons
    compareButton.setText(if option == "Icon" then "⇄" else "Send to Comparison")
    compareButton.setVisible(option != "Off")
    compareButton.setManaged(option != "Off")
  refreshComparisonOptions()
  private val resultButtons = W.hbox(
    6, compareButton,
    W.button("⇢ img2img", "Use the result as img2img init image")(Option(result.get).filter(_.nonEmpty).foreach(p => ctx.sendToTab(Mode.Img2Img, Paths.get(p), None))),
    W.button("⇢ Inpaint", "Use the result for inpainting")(Option(result.get).filter(_.nonEmpty).foreach(p => ctx.sendToTab(Mode.Inpaint, Paths.get(p), None))),
    W.iconButton("⧉", "Copy the result")(Option(result.get).filter(_.nonEmpty).foreach(p => ImageActions.copyImage(Paths.get(p)))),
    W.iconButton("▤", "Show in folder")(Option(result.get).filter(_.nonEmpty).foreach(p => ImageActions.openFolder(Paths.get(p))))
  )

  val node: ScrollPane =
    val v = new VBox(
      10,
      W.card("Image", drop.node, f.grid, W.hbox(8, run, spinner)),
      W.card("Result", resultView, resultInfo, resultButtons)
    )
    VBox.setVgrow(resultView, Priority.ALWAYS)
    v.setPadding(new Insets(10, 12, 16, 12))
    val sp = new ScrollPane(v)
    sp.setFitToWidth(true)
    sp.setHbarPolicy(ScrollPane.ScrollBarPolicy.NEVER)
    sp
